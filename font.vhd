  function GetChar
    (X: std_logic_vector(2 downto 0);
     Y:  std_logic_vector(3 downto 0);
	  I: std_logic_vector(7 downto 0))
    return std_logic is

	 variable char: std_logic_vector(7 downto 0);
	 
	 
  begin

	 char := ROM((16*to_integer(unsigned(I)))+to_integer(unsigned(Y)));
    return char(7-to_integer(unsigned(X)));
  end GetChar;
  
  
  function Hex2ASCII
    (nibble: std_logic_vector(3 downto 0))
    return std_logic_vector is
	 
	 begin
	 
	 case nibble is
     when "0000" => return "0110000";
     when "0001" => return "0110001";
     when "0010" => return "0110010";
     when "0011" => return "0110011";
	  
     when "0100" => return "0110100";
     when "0101" => return "0110101";
     when "0110" => return "0110110";
     when "0111" => return "0110111";
	  
     when "1000" => return "0111000";
     when "1001" => return "0111001";
     when "1010" => return "1000001";
     when "1011" => return "1000010";
	  
     when "1100" => return "1000011";
     when "1101" => return "1000100";
     when "1110" => return "1000101";
     when "1111" => return "1000110";	  
	  
   end case;
	 
	 end Hex2ASCII;
	 
	 

